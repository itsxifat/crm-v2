const optStr = (max) => z.string().max(max).optional().nullable()

const transactionSchema = z.object({
  type:           z.enum(['INCOME', 'EXPENSE']),
  category:       z.string().min(1),
  amount:         z.coerce.number().positive(),
  description:    z.string().min(1),
  date:           z.string(),
  reference:      z.string().optional().nullable(),
  projectId:        z.string().optional().nullable(),
  invoiceId:        z.string().optional().nullable(),
  clientId:         z.string().optional().nullable(),
  vendorId:         z.string().optional().nullable(),
  freelancerId:     z.string().optional().nullable(),
  agencyId:         z.string().optional().nullable(),
  paidToEmployeeId: z.string().optional().nullable(),
  paidToName:       z.string().optional().nullable(),
  // Multi-currency: amount is in `currency`; for non-BDT, amountBDT is the
  // manually-entered BDT-equivalent actually spent/received. All metrics roll up in BDT.
  currency:       z.string().default(BASE_CURRENCY).refine(isValidCurrency, 'Unsupported currency'),
  amountBDT:      z.coerce.number().positive().optional().nullable(),
  vendor:         z.string().optional().nullable(),
  paidBy:         z.string().optional().nullable(),
  accountManager: z.string().optional().nullable(),
  paymentMethod:   z.string().optional().nullable(),
  expenseCategory: z.string().optional().nullable(),
  receiptUrl:      z.string().optional().nullable(),
  // txnId provided manually only when no receipt; otherwise auto-generated by pre-save hook
  txnId:          z.string().optional().nullable(),
  // Money account the cash landed in (required for entries dated on/after go-live).
  accountId:      optStr(64),
  // Manual entries are operating income only; capital, loans, transfers etc. are
  // recorded under Finance → Money accounts (movements / transfers).
  kind:           z.enum(['OPERATING']).optional().nullable(),
  channel:        optStr(40),
  cheque:         z.object({ no: optStr(60), date: optStr(40), bank: optStr(120) }).optional().nullable(),
  // Business unit: 'VENTURE:<id>' | 'PRODUCT:<id>' | 'COMPANY' (required; checked against the config below).
  unit:           optStr(80),
}).superRefine((d, ctx) => {
  if (d.currency !== BASE_CURRENCY && !d.amountBDT) {
    ctx.addIssue({ path: ['amountBDT'], code: 'custom', message: 'Enter the BDT-equivalent for a non-BDT transaction' })
  }
})

const POPULATE = [
  { path: 'paidBy',         select: 'name avatar' },
  { path: 'accountManager', select: 'name avatar' },
  { path: 'createdBy',      select: 'name' },
  { path: 'projectId',      select: 'name projectCode venture' },
  { path: 'accountId',      select: 'name type last4 currency bankName mfsProvider' },
  { path: 'counterAccountId', select: 'name type last4 currency' },
]

// ObjectId reference fields: a malformed id would otherwise fail as a 500 CastError.
const REF_FIELDS = ['projectId', 'invoiceId', 'agencyId', 'paidToEmployeeId', 'paidBy', 'accountManager']

const errorJson = (err, txnId) => {
  const mapped = httpErrorPayload(err, { txnId })
  return mapped ? NextResponse.json(mapped.body, { status: mapped.status }) : null
}

// GET /api/transactions
// Filters: type, category, subcategory, startDate, endDate (Dhaka days, inclusive),
// accountId (id | 'none' for rows without a money account), kind (one or a comma
// list of TX_KINDS; OPERATING also matches legacy rows without a kind),
// clearStatus, invoiceId, unit (an exact unit, or UNASSIGNED for untagged rows),
// page, limit. Users without finance.units.all see only their own venture's rows.
export async function GET(request) {
  try {
    const session = await getServerSession(authOptions)
    const denied  = requirePerm(session, 'finance.transactions.view')
    if (denied) return denied
    await connectDB()

    const { searchParams } = new URL(request.url)
    const page      = Math.max(1, parseInt(searchParams.get('page')  ?? '1',  10) || 1)
    const limit     = Math.min(1000, Math.max(1, parseInt(searchParams.get('limit') ?? '50', 10) || 50))
    const type      = searchParams.get('type')
    const category  = searchParams.get('category')
    const subcategory = searchParams.get('subcategory')
    const startDate = searchParams.get('startDate')
    const endDate   = searchParams.get('endDate')
    const accountId = searchParams.get('accountId')
    const kindParam = searchParams.get('kind')
    const clearStatus = searchParams.get('clearStatus')
    const invoiceId = searchParams.get('invoiceId')
    const unitParam = readUnitParam(searchParams)
    if (unitParam.error) return NextResponse.json({ error: unitParam.error }, { status: 400 })
    const skip      = (page - 1) * limit

    // category & subcategory are plain fields — match by direct equality.
    // (subcategory is stored in the `expenseCategory` field for both income & expense.)
    const filter = {}
    const and = []
    if (type)        filter.type            = type
    if (category)    filter.category        = category
    if (subcategory) filter.expenseCategory = subcategory
    // Date-only filters are Asia/Dhaka calendar days; the end day is inclusive.
    if (startDate || endDate) {
      filter.date = {}
      if (startDate) filter.date.$gte = parseDhakaDay(startDate)?.start ?? new Date(startDate)
      if (endDate) {
        const end = parseDhakaDay(endDate)
        if (end) filter.date.$lt  = end.next
        else     filter.date.$lte = new Date(endDate)
      }
      for (const k of ['$gte', '$lt', '$lte']) {
        if (filter.date[k] && Number.isNaN(filter.date[k].getTime()))
          return NextResponse.json({ error: 'Invalid date filter' }, { status: 400 })
      }
    }
    if (accountId) {
      if (accountId === 'none') filter.accountId = null
      else if (isValidObjectId(accountId)) filter.accountId = accountId
      else return NextResponse.json({ error: 'Invalid accountId' }, { status: 400 })
    }
    if (kindParam) {
      const kinds = [...new Set(kindParam.split(',').map(k => k.trim().toUpperCase()).filter(Boolean))]
      const bad = kinds.filter(k => !TX_KINDS.includes(k))
      if (bad.length) return NextResponse.json({ error: `Unknown kind: ${bad.join(', ')}` }, { status: 400 })
      if (kinds.length) {
        if (kinds.includes('OPERATING')) {
          and.push({ $or: [{ kind: { $in: kinds } }, { kind: { $exists: false } }, { kind: null }] })
        } else {
          filter.kind = { $in: kinds }
        }
      }
    }
    if (clearStatus) {
      if (!CLEAR_STATUSES.includes(clearStatus)) return NextResponse.json({ error: 'Invalid clearStatus' }, { status: 400 })
      if (clearStatus === 'UNCLEARED') and.push({ $or: [{ clearStatus: 'UNCLEARED' }, { clearStatus: { $exists: false } }, { clearStatus: null }] })
      else filter.clearStatus = clearStatus
    }
    if (invoiceId) {
      if (!isValidObjectId(invoiceId)) return NextResponse.json({ error: 'Invalid invoiceId' }, { status: 400 })
      filter.invoiceId = invoiceId
    }
    if (and.length) filter.$and = and

    const scope = await financeScope(session)
    const query = unitFilter(filter, scope, unitParam.unit)
    const sort  = { date: -1, createdAt: -1 }

    const [transactions, total] = await Promise.all([
      Transaction.find(query).skip(skip).limit(limit).sort(sort).populate(POPULATE),
      Transaction.countDocuments(query),
    ])

    // Rows on this page that a later entry reversed (reversedBy = that entry's txnId),
    // so the page can show them as reversed and offer no second reversal.
    const reversals = transactions.length
      ? await Transaction.find({ reversalOf: { $in: transactions.map(t => t._id) } }).select('reversalOf txnId').lean()
      : []
    const reversedBy = new Map(reversals.map(r => [String(r.reversalOf), r.txnId ?? String(r._id)]))

    return NextResponse.json({
      data: transactions.map(t => ({ ...t.toJSON(), reversedBy: reversedBy.get(String(t._id)) ?? null })),
      meta: { page, limit, total, pages: Math.ceil(total / limit), scope: { all: !!scope.all } },
    })
  } catch (err) {
    console.error('[GET /api/transactions]', err)
    return NextResponse.json({ error: 'Internal server error' }, { status: 500 })
  }
}

// POST /api/transactions — manual INCOME entry.
// Body: the schema above. `accountId` is required for entries dated on/after the
// finance go-live date. Linking an issued invoice (SENT / PARTIALLY_PAID /
// OVERDUE) credits it atomically and the project with it; the VAT/SD share of a
// VAT invoice is kept out of the P&L. The amount may not exceed the invoice's
// outstanding balance (less pending payment requests) — an over-receipt is a
// client advance, recorded as a separate unlinked entry, never invoice revenue.
// Draft invoices cannot take payments; PAID / CANCELLED invoices are linked only.
// `unit` (the venture / product / Company the income belongs to) is required. A
// payment credited to an invoice is booked under the invoice's unit (its own,
// else its project's venture, else Company), like every other settlement.
export async function POST(request) {
  let txnIdForError = null
  try {
    const session = await getServerSession(authOptions)
    const denied  = requirePerm(session, 'finance.transactions.create')
    if (denied) return denied
    await connectDB()

    let body
    try { body = await request.json() } catch { return NextResponse.json({ error: 'Invalid JSON body' }, { status: 400 }) }
    const parsed = transactionSchema.safeParse(body ?? {})
    if (!parsed.success)
      return NextResponse.json({ error: 'Validation failed', details: parsed.error.flatten() }, { status: 422 })

    // `kind` can only be OPERATING (the default), so it is not read further.
    const { date, accountId: rawAccountId, channel, cheque, unit: rawUnit, ...rest } = parsed.data

    // Expenses are never written to the ledger directly — they must go through
    // the expense-request pipeline (/api/expenses → Paid → Authorized), which
    // creates the EXPENSE transaction when the expense is paid.
    if (rest.type === 'EXPENSE')
      return NextResponse.json({ error: 'Expenses cannot be added directly. Submit an expense request instead.' }, { status: 422 })

    // Business unit: required, and must be Company or a configured venture / product.
    let unit = rawUnit?.trim() || null
    if (!unit)
      return NextResponse.json({ error: 'Choose the venture or product this income belongs to', field: 'unit' }, { status: 422 })
    if (!isValidUnit(unit, await getConfig()))
      return NextResponse.json({ error: 'Unknown venture or product', field: 'unit' }, { status: 422 })

    const txDate = parseBusinessDate(date)
    if (!txDate)
      return NextResponse.json({ error: 'Invalid date' }, { status: 422 })
    // Money cannot be received on a day that has not happened yet (Asia/Dhaka).
    if (dhakaDayKey(txDate) > dhakaDayKey(new Date()))
      return NextResponse.json({ error: 'The date cannot be in the future', field: 'date' }, { status: 422 })

    // txnId, receipt, reference, project etc. are all optional —
    // the pre-save hook auto-generates a txnId when none is provided.

    // Strip empty strings to null
    const clean = Object.fromEntries(
      Object.entries(rest).map(([k, v]) => [k, v === '' ? null : v])
    )
    txnIdForError = clean.txnId ?? null
    if (!clean.txnId) delete clean.txnId
    const badRef = REF_FIELDS.find(k => clean[k] != null && !isValidObjectId(clean[k]))
    if (badRef) return NextResponse.json({ error: `Invalid ${badRef}`, field: badRef }, { status: 422 })

    // BDT-equivalent: for BDT the amounts are identical; for foreign currency use
    // the manually-entered value (validated above).
    const amountBDT = clean.currency === BASE_CURRENCY ? clean.amount : clean.amountBDT

    // Amount of this transaction expressed in `targetCurrency`, or null when it
    // cannot be converted (foreign → a different foreign currency).
    const amountIn = (targetCurrency) => {
      const cur = targetCurrency || BASE_CURRENCY
      if (cur === clean.currency) return clean.amount
      if (cur === BASE_CURRENCY)  return amountBDT
      return null
    }

    // Money account + books lock + go-live rule, before anything is written.
    const accountId = rawAccountId?.trim() || null
    try {
      if (accountId) await loadPostingAccount(accountId, { currency: clean.currency, date: txDate })
      await preflightPosting({ date: txDate, accountId, cash: clean.amount })
    } catch (err) {
      const res = errorJson(err)
      if (res) return res
      throw err
    }

    // Validate the invoice link BEFORE writing the ledger row, so a bad link can
    // never leave an orphan income entry behind.
    let invoice = null, invoiceCredit = null
    if (clean.invoiceId) {
      if (!isValidObjectId(clean.invoiceId))
        return NextResponse.json({ error: 'Invalid invoiceId' }, { status: 400 })
      invoice = await Invoice.findById(clean.invoiceId).lean()
      if (!invoice) return NextResponse.json({ error: 'Invoice not found' }, { status: 404 })
      if (invoice.status === 'DRAFT')
        return NextResponse.json({ error: `${invoiceLabel(invoice)} is still a draft — send it before recording a payment against it` }, { status: 422 })
      if (PAYABLE_INVOICE_STATUSES.includes(invoice.status)) {
        invoiceCredit = amountIn(invoice.currency)
        if (invoiceCredit == null)
          return NextResponse.json({
            error: `This invoice is in ${invoice.currency}. Record the payment in ${invoice.currency} or ${BASE_CURRENCY} to link it.`,
          }, { status: 422 })
        // invoiceCredit is in the invoice currency, like the balance. Money in
        // pending payment requests is already claimed against the invoice.
        const pending = await pendingPaymentTotal({ invoiceId: invoice._id })
        const outstanding = Math.max(0, round2(invoiceOutstanding(invoice) - pending))
        if (invoiceCredit > outstanding + 0.01)
          return NextResponse.json({
            error: `Amount exceeds ${invoiceLabel(invoice)}'s outstanding balance of ${invoice.currency || BASE_CURRENCY} ${outstanding.toFixed(2)}${pending > 0 ? ' (after pending payment requests)' : ''} — record any excess as a separate income entry without the invoice`,
            field: 'amount',
          }, { status: 409 })
      }
    }

    const entry = { ...clean }
    for (const k of ['amount', 'currency', 'amountBDT', 'type', 'kind']) delete entry[k]

    let transaction
    const chosenUnit = unit
    if (invoice && invoiceCredit != null) {
      // Revenue on an invoice belongs to the invoice's unit, whatever was picked.
      unit = (await invoiceUnits([invoice])).get(String(invoice._id)) ?? unit
      // Credit the invoice (atomic — refused if a concurrent payment took the
      // balance meanwhile) and the project, as the other payment paths do.
      const projectId = invoice.projectId ?? (clean.projectId && isValidObjectId(clean.projectId) ? clean.projectId : null)
      try {
        const result = await settleInvoicePayment({
          invoice,
          projectId,
          cash:          clean.amount,
          currency:      clean.currency,
          cashBDT:       amountBDT,
          invoiceCredit,
          date:          txDate,
          paidAt:        txDate,
          accountId,
          channel:       channel || null,
          cheque:        cheque || null,
          entry:         { ...entry, unit, createdBy: session.user.id },
          userId:        session.user.id,
        })
        transaction = result.transaction
      } catch (err) {
        const res = errorJson(err, txnIdForError)
        if (res) return res
        throw err
      }
    } else {
      try {
        transaction = await postMoneyEntry({
          ...entry,
          unit,
          type:      'INCOME',
          kind:      'OPERATING',
          amount:    clean.amount,
          currency:  clean.currency,
          amountBDT,
          date:      txDate,
          accountId,
          channel:   channel || null,
          cheque:    cheque || null,
          createdBy: session.user.id,
        }, { userId: session.user.id })
      } catch (err) {
        const res = errorJson(err, txnIdForError)
        if (res) return res
        throw err
      }
    }

    const saved = await Transaction.findById(transaction._id).populate(POPULATE)

    logActivity({
      userId:   session.user.id,
      userRole: session.user.role,
      action:   'CREATE',
      entity:   'TRANSACTION',
      entityId: transaction._id.toString(),
      changes:  JSON.stringify({
        type: 'INCOME', amount: clean.amount, currency: clean.currency, category: clean.category,
        accountId, invoiceId: clean.invoiceId ?? null, invoiceCredited: invoiceCredit != null,
        unit, ...(unit !== chosenUnit ? { unitChosen: chosenUnit } : {}),
      }),
      request,
    })

    return NextResponse.json({ data: (saved ?? transaction).toJSON() }, { status: 201 })
  } catch (err) {
    const res = errorJson(err, txnIdForError)
    if (res) return res
    console.error('[POST /api/transactions]', err)
    return NextResponse.json({ error: 'Internal server error' }, { status: 500 })
  }
}
